"""Regenerate descriptive tables from validated JSONL rows, never from prose."""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
from dataclasses import asdict
import json
import math
from pathlib import Path
import sqlite3
import statistics
import subprocess

from .classify import FAILURES
from .runner import load_tasks, read_rows


def wilson(successes: int, total: int) -> tuple[float, float] | None:
    if not total:
        return None
    z = 1.959963984540054
    p, scale = successes / total, 1 + z*z/total
    center = (p + z*z/(2*total)) / scale
    radius = z * math.sqrt(p*(1-p)/total + z*z/(4*total*total)) / scale
    return max(0., center-radius), min(1., center+radius)


def bucket(lines: int) -> str:
    return "1" if lines == 1 else "2–3" if lines <= 3 else "4–8" if lines <= 8 else "9+"


def report_directory(value: str) -> Path:
    directory = Path(value)
    if directory.parts and directory.parts[0] == "results" and Path("eval").is_dir():
        directory = Path("eval") / directory
    return directory


def table(headers: list[str], rows: list[list]) -> str:
    def cell(value: object) -> str:
        return str(value).replace("|", "\\|").replace("\n", " ")
    return "\n".join(["| " + " | ".join(headers) + " |",
                      "| " + " | ".join("---" for _ in headers) + " |"] +
                     ["| " + " | ".join(map(cell, row)) + " |" for row in rows]) + "\n"


def proportion(rows: list[dict]) -> str:
    n = len(rows)
    s = sum(r["proved"] for r in rows)
    return f"{s}/{n} ({100*s/n:.1f}%)" if n else "NA (0 completed)"


def prepare_partial(directory: Path, config: dict, reason: str) -> None:
    """Report an unavailable run without reserving its run_id or starting its clock."""
    if (directory / "manifest.json").exists():
        return
    from .agent import atomic_json
    directory.mkdir(parents=True, exist_ok=True)
    tasks = load_tasks(config)
    atomic_json(directory / "report_context.json", {
        "config": config, "tasks": [asdict(t) for t in tasks],
        "isabelle_version": subprocess.check_output(["isabelle", "version"], text=True).strip(),
        "git_sha": subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip()})
    (directory / "results.jsonl").touch(exist_ok=True)
    atomic_json(directory / "status.json", {
        "status": reason, "written": 0, "completed": len(read_rows(directory / "results.jsonl")),
        "planned": len(tasks)*len(config["conditions"]),
        "usd_reserved_or_spent": config.get("prior_usd_cost", 0)})


def generate(directory: Path) -> str:
    own = read_rows(directory / "results.jsonl")
    manifest_path = directory / "manifest.json"
    if not manifest_path.exists():
        manifest_path = directory / "report_context.json"
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else {}
    config = manifest.get("config", {})
    tasks = manifest.get("tasks", [])
    wanted = {t["id"] for t in tasks}
    baseline_path = directory.parent / "tactics" / "results.jsonl"
    baseline = [] if directory.name == "tactics" else read_rows(baseline_path)
    if wanted:
        baseline = [r for r in baseline if r["lemma_id"] in wanted]
    # Test fakes are never evidence of real-model performance.
    excluded = sum(r.get("provider") == "fake" for r in own)
    rows = [r for r in own + baseline if r.get("provider") != "fake"]
    groups: dict[tuple, list[dict]] = defaultdict(list)
    for r in rows:
        groups[(r["condition"]["model"], r["condition"]["max_attempts"], r["stratum"])].append(r)
    planned = Counter(t["stratum"] for t in tasks)
    for condition in config.get("conditions", []):
        if condition["provider"] != "fake":
            for stratum in planned:
                groups.setdefault((condition["model"], condition["max_attempts"], stratum), [])
    ordered = sorted(groups, key=lambda k: (k[0] != "tactics", k))
    out = [f"# Evaluation summary: {directory.name}\n",
           "Generated by `python -m eval.harness.report " + str(directory) + "`.\n"]
    if config:
        out.append(f"Configuration: max_usd={config['max_usd']}, "
                   f"max_hours={config.get('max_hours', 8)}, workers={config['workers']}, "
                   f"kernel_timeout_s={config['kernel_timeout_s']}, "
                   f"max_completion_tokens={config.get('max_completion_tokens', 2048)}. "
                   "Real requests default to temperature 0; per-condition exceptions, if any, "
                   "are recorded in the config and request trace.\n")
    out.append("Loop limits: at most 40 feedback lines and 3000 feedback characters per retry; "
               "8000 characters each for proof and auxiliary text. The tactic battery allows "
               "8 methods with a 30-second timeout for each separate check.\n")
    real = [r for r in own if r.get("provider") not in {"fake", "tactics"}]
    if not real:
        out.append("**No completed real-model observations. This is a baseline-only/partial report, "
                   "not a measurement of LLM proof performance.**\n")
    status_path = directory / "status.json"
    if status_path.exists():
        status = json.loads(status_path.read_text())
        spent = status["usd_reserved_or_spent"]
        ledger = directory / "budget.sqlite"
        if ledger.exists():
            with sqlite3.connect(ledger) as db:
                spent = config.get("prior_usd_cost", 0) + db.execute(
                    "SELECT COALESCE(SUM(usd),0) FROM calls").fetchone()[0]
        out.append(f"Last recorded run status: `{status['status']}`. Completed rows: {len(own)}/"
                   f"{status['planned']}. Reserved/spent LLM budget: "
                   f"${spent:.6f} (includes prior smoke spending and unfinished-call reservations).\n")
    out.append("Strata are never pooled. Percentages use completed rows; coverage is shown separately. "
               "Wilson intervals are descriptive, unadjusted 95% intervals; related example steps "
               "are not independent random samples. Incomplete runs may omit slower or harder tasks; "
               "their completed-row rates are not full-corpus estimates. Fake-provider rows excluded: "
               + str(excluded) + ".\n")
    out.append("## Table 1 — kernel-accepted proofs\n")
    counts = []
    for model, attempts, stratum in ordered:
        group = groups[model, attempts, stratum]
        n, successes = len(group), sum(r["proved"] for r in group)
        ci = wilson(successes, n)
        counts.append([model, attempts, stratum, f"{n}/{planned.get(stratum, n)}",
                       proportion(group), f"{100*ci[0]:.1f}–{100*ci[1]:.1f}%" if ci else "NA"])
    out.append(table(["Model", "Max attempts", "Stratum", "Completed/planned", "Proved", "Wilson 95% CI"], counts))
    out.append("## Table 2 — value over tactics\n")
    battery = {r["lemma_id"]: r["proved"] for r in rows if r["condition"]["model"] == "tactics"}
    comparisons = []
    for key in ordered:
        if key[0] == "tactics":
            continue
        paired = [r for r in groups[key] if r["lemma_id"] in battery]
        comparisons.append([*key, len(paired),
                            sum(r["proved"] and not battery[r["lemma_id"]] for r in paired),
                            sum(not r["proved"] and battery[r["lemma_id"]] for r in paired)])
    out.append(table(["Model", "Max attempts", "Stratum", "Paired completed",
                      "Model only", "Tactics only"], comparisons))
    if not comparisons:
        out.append("NA: no completed real-model comparison is available.\n")
    out.append("## Table 3 — failed attempts by class\n")
    failures = []
    for key in ordered:
        counter = Counter()
        for row in groups[key]:
            counter.update(row["attempt_failures"])
        total = sum(counter.values())
        failures.append([*key, *[counter[f] for f in FAILURES], total,
                         f"{counter['unknown_fact']}/{total} ({100*counter['unknown_fact']/total:.1f}%)"
                         if total else "NA (no failed attempts)"])
    out.append(table(["Model", "Max attempts", "Stratum", *FAILURES, "Failed attempts",
                      "Hallucinated-fact rate"], failures))
    out.append("The requested hallucinated-fact proxy is **unknown_fact / failed attempts**, "
               "including unsuccessful retries before an eventual proof. This classifier also "
               "covers unknown types/undeclared names; it does not establish hallucination causally.\n")
    out.append("## Table 4 — original-proof length\n")
    out.append(table(["Model", "Max attempts", "Stratum", "1 line", "2–3 lines", "4–8 lines", "9+ lines"],
                     [[*key, *[proportion([r for r in groups[key] if bucket(r["orig_proof_lines"]) == b])
                               for b in ["1", "2–3", "4–8", "9+"]]] for key in ordered]))
    out.append("## Table 5 — cost and elapsed time\n")
    costs = []
    for key in ordered:
        group = groups[key]
        successes = sum(r["proved"] for r in group)
        cost = sum(r["usd_cost"] for r in group)
        gpu = sum(r["gpu_hours"] for r in group) if group and all(
            r.get("gpu_hours") is not None for r in group) else None
        bound = " (upper bound)" if any(r["cost_is_upper_bound"] for r in group) else ""
        median = lambda field: f"{statistics.median(r[field] for r in group):.3f}" if group else "NA"
        costs.append([*key, f"${cost:.6f}" + bound,
                      f"${cost/successes:.6f}" + bound if successes else "NA",
                      f"{gpu/successes:.6f}" if gpu is not None and successes else "NA",
                      median("llm_wall_s"), median("kernel_wall_s")])
    out.append(table(["Model", "Max attempts", "Stratum", "Row USD", "USD/proved", "GPU-h/proved",
                      "Median LLM s/lemma", "Median kernel s/lemma"], costs))
    out.append("Times are sums across attempts per completed lemma, then medians across lemmas. "
               "USD values are token-cost estimates at configured prices, not invoices; local CPU "
               "and engineering costs are excluded. "
               "Row cost excludes unfinished rows; the run budget above includes reservations. "
               "GPU time is NA unless measured allocation hours are recorded; LLM latency is not "
               "silently presented as GPU usage. A zero USD price alone does not imply free compute.\n")
    out.append("## Methods in accepted proofs\n")
    methods = "simp auto blast metis fastforce force arith linarith induction try0 other".split()
    method_rows = []
    for key in ordered:
        counter = Counter()
        for row in groups[key]:
            if row["proved"]:
                counter.update(row["methods_used"])
        method_rows.append([*key, *[counter[m] for m in methods]])
    out.append(table(["Model", "Max attempts", "Stratum", *methods], method_rows))
    out.append("Method counts are lexical occurrences in the final accepted proof and auxiliaries; "
               "`induct` is grouped with `induction`. They are not kernel execution counts. "
               "The battery uses the literal requested methods without a `using assms` preface; "
               "statements with named assumptions may therefore be disadvantaged. "
               "These rates measure this fixed battery, not mathematical difficulty alone.\n")
    out.append("## Provenance and limitations\n")
    provenance = []
    for key in ordered:
        group = groups[key]
        provenance.append([*key, ", ".join(sorted({i for r in group for i in r["model_ids_returned"]})) or "NA",
                           ", ".join(sorted({r["isabelle_version"] for r in group})) or "NA",
                           ", ".join(sorted({r["git_sha"] for r in group})) or "NA"])
    out.append(table(["Model", "Max attempts", "Stratum", "Returned API model ids",
                      "Isabelle", "Git SHA"], provenance))
    out.append("`lib` statements and proofs are public distribution material and may be in model "
               "training data. Imported Main/Complex_Main also retain original facts and simp rules: "
               "this is reconstruction in that environment. The `fresh` label currently means "
               "repository example-derived steps, with no verified training-data novelty. "
               "No hand-written fresh_statements.thy was supplied. Corpus filtering favours statements "
               "and original proofs that validate within the documented selection bounds. "
               "These limitations preclude a contamination-free generalization claim.\n")
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory")
    parser.add_argument("--config", help="Describe a partial run without launching it")
    args = parser.parse_args()
    directory = report_directory(args.directory)
    directory.mkdir(parents=True, exist_ok=True)
    if args.config:
        prepare_partial(directory, json.loads(Path(args.config).read_text()), "real_models_unavailable")
    output = generate(directory)
    (directory / "summary.md").write_text(output)
    print(output, end="")


if __name__ == "__main__":
    main()
